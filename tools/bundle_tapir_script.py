#!/usr/bin/env python3
"""
Bundle the Archicad side into one self-contained script for Tapir's script palette.

  python3 tools/bundle_tapir_script.py          -> archicad/KitchenBuild.py
  python3 tools/bundle_tapir_script.py --check  exit 1 when KitchenBuild.py is out of date

The palette runs a single file (`uv run --script KitchenBuild.py --port N`), so the
library (archicad/build_kitchen.py) and the window (archicad/kitchen_gui.py) are
concatenated into one module. Edit those two files, not the bundle.
"""
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIB, GUI, OUT = ROOT / "archicad" / "build_kitchen.py", ROOT / "archicad" / "kitchen_gui.py", ROOT / "archicad" / "KitchenBuild.py"


def body(src):
    src = re.sub(r"^#!.*\n", "", src)
    src = src.replace("from __future__ import annotations\n", "")
    return re.split(r'\nif __name__ == "__main__":\n', src)[0].rstrip() + "\n"


def bundle():
    lib, gui = LIB.read_text(encoding="utf-8"), GUI.read_text(encoding="utf-8")
    digest = hashlib.sha256((lib + gui).encode()).hexdigest()[:12]
    return f'''#!/usr/bin/env python3
# /// script
# requires-python = ">=3.8"
# dependencies = []
# ///
"""Kitchen Configurator: build a kitchen from the web app's build file in the open Archicad project.

Run it from Tapir's script palette in Archicad (it opens a window), by double-clicking, or from a console:
  python KitchenBuild.py                                   the window
  python KitchenBuild.py BUILD.kitchen-build.json [--mode append|replace] [--story N] [--yes]
  python KitchenBuild.py --status | --builds | --remove RUN_ID
Talks only to Archicad/Tapir on 127.0.0.1:19723-19744. Standard library only.

Single-file build {digest}, generated by tools/bundle_tapir_script.py from archicad/build_kitchen.py and
archicad/kitchen_gui.py - edit those, not this file.
"""
from __future__ import annotations

KITCHEN_BUNDLE = True
KITCHEN_BUILD = "{digest}"

# ==================== build_kitchen.py ====================
{body(lib)}
import sys as _sys  # noqa: E402

B = _sys.modules[__name__]  # the window below uses the library above through B

# ==================== kitchen_gui.py ====================
{body(gui)}

if __name__ == "__main__":
    sys.exit(gui_main())
'''


if __name__ == "__main__":
    text = bundle()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            sys.exit("archicad/KitchenBuild.py is out of date: run python3 tools/bundle_tapir_script.py")
        print("archicad/KitchenBuild.py is up to date.")
    else:
        OUT.write_text(text, encoding="utf-8")
        print(f"Wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
